export type TranslationKey = keyof typeof TRANSLATIONS.en_US;

export function resolveLocale(
  languageSetting: string,
  browserLang?: string
): LocaleCode {
  if (languageSetting && languageSetting !== 'System Auto') {
    if (languageSetting in TRANSLATIONS) {
      return languageSetting as LocaleCode;
    }
  }
  const nav = (
    browserLang ??
    (typeof navigator !== 'undefined' ? navigator.language : 'en-US')
  ).toLowerCase();
  if (nav.startsWith('es')) return 'es_ES';
  if (nav.startsWith('pt')) return 'pt_BR';
  if (nav.startsWith('fr')) return 'fr_FR';
  if (nav.startsWith('it')) return 'it_IT';
  if (nav.startsWith('nl')) return 'nl_NL';
  if (nav.startsWith('ja')) return 'ja_JP';
  if (nav.startsWith('zh')) return 'zh_CN';
  if (nav.startsWith('ar')) return 'ar_SA';
  return 'en_US';
}

export function createTranslator(languageSetting: string) {
  const locale = resolveLocale(languageSetting);
  const dict = (TRANSLATIONS[locale] ?? TRANSLATIONS.en_US) as Record<string, string>;
  const fallback = TRANSLATIONS.en_US as Record<string, string>;
  return {
    locale,
    isRtl: locale === 'ar_SA',
    t: (key: TranslationKey): string => dict[key] ?? fallback[key],
  };
}

interface I18nContextValue {
  locale: LocaleCode;
  isRtl: boolean;
  t: (key: TranslationKey) => string;
}

const I18nContext = createContext<I18nContextValue>(
  createTranslator('System Auto')
);

export const I18nProvider: React.FC<{
  language: string;
  children: React.ReactNode;
}> = ({ language, children }) => {
  const value = useMemo(() => createTranslator(language), [language]);
  return React.createElement(I18nContext.Provider, { value }, children);
};

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
